#!/usr/bin/env node
/**
 * Write the build fingerprint (decision 7: running-instance update hint).
 *
 * Two artifacts, same value:
 *
 * - `src/build-fingerprint.ts` — a generated module baked into the compiled
 *   output; the loaded code's own identity.
 * - `lib/build-fingerprint.json` — the disk fingerprint the plugin reads once
 *   at startup; the latest build's identity.
 *
 * The id is a content digest over the build INPUTS (src sources, configs,
 * package.json, git HEAD when available) — never the build output — so a
 * rebuild with unchanged inputs produces the same id and cannot false-positive
 * a stale instance. `buildTime` is metadata only and never compared.
 *
 * The script runs before tsc (the generated module must compile in) and writes
 * the JSON into lib/ at the same time; neither tsc nor tsdown (`clean: false`)
 * cleans lib/, so the JSON survives to the end of the build.
 */

import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC_DIR = join(ROOT, 'src')
const LIB_DIR = join(ROOT, 'lib')
const GENERATED_FILE = join(SRC_DIR, 'build-fingerprint.ts')
const DISK_FILE = join(LIB_DIR, 'build-fingerprint.json')

/** Every source/config file the fingerprint must cover (sorted, stable order). */
function inputFiles() {
  const sources = []
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry)
      if (statSync(full).isDirectory()) {
        walk(full)
      } else if (/\.(ts|tsx)$/.test(entry)) {
        sources.push(full)
      }
    }
  }
  walk(SRC_DIR)
  return [
    join(ROOT, 'package.json'),
    join(ROOT, 'tsconfig.json'),
    join(ROOT, 'tsconfig.client.json'),
    join(ROOT, 'tsdown.config.ts'),
    ...sources.filter(file => relative(SRC_DIR, file) !== 'build-fingerprint.ts'),
  ]
}

/** Stable content digest of the build inputs. */
function contentDigest(files) {
  const hash = createHash('sha256')
  for (const file of files.sort((a, b) => a.localeCompare(b))) {
    const rel = relative(ROOT, file).replace(/\\/g, '/')
    hash.update(`${rel}\0`)
    hash.update(readFileSync(file))
    hash.update('\0')
  }
  return hash.digest('hex').slice(0, 16)
}

/** Short git HEAD, or null when the checkout has no git or no commit yet. */
function gitHead() {
  try {
    const head = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: ROOT,
      encoding: 'utf8',
    }).trim()
    return head === '' ? null : head
  } catch {
    return null
  }
}

const id = contentDigest(inputFiles())
const buildTime = new Date().toISOString()
const gitCommit = gitHead()

const generatedSource = `/**
 * GENERATED by scripts/write-build-fingerprint.mjs — do not edit; the build
 * overwrites this file on every \`pnpm build\`. The committed stub (all nulls)
 * keeps source-mode compilation and CI (test-before-build) working on a fresh
 * checkout; a null id means "unknown", which isInstanceStale treats as not stale.
 */
import type { BuildFingerprint } from './fingerprint.ts'

/** The build-time identity of THIS compiled code (decision 7). */
export const BUILD_FINGERPRINT: BuildFingerprint = {
  id: ${JSON.stringify(id)},
  buildTime: ${JSON.stringify(buildTime)},
  gitCommit: ${JSON.stringify(gitCommit)},
}
`

mkdirSync(LIB_DIR, { recursive: true })
writeFileSync(GENERATED_FILE, generatedSource)
writeFileSync(DISK_FILE, `${JSON.stringify({ id, buildTime, gitCommit }, null, 2)}\n`)
console.log(`[build-fingerprint] id=${id} git=${gitCommit ?? '-'} time=${buildTime}`)
